/**
 * @file tts_rules.h
 * @brief English letter-to-sound rules for tts.c, in the style of the NRL rules (Elovitz, Johnson, McHugh and Shore, 1976), written afresh.
 *
 * A rule is `left [match] right = phonemes`: the letters in `match` say
 * `phonemes` when the letters around them fit `left` and `right`. The first
 * rule that fits wins, so the special cases come first and each letter ends
 * with its plain sound. In the contexts:
 *
 * | symbol | fits |
 * |--------|------|
 * | (space) | the edge of the word |
 * | #      | one or more vowels (A E I O U) |
 * | :      | none or more consonants |
 * | ^      | one consonant |
 * | .      | one voiced consonant (B D V G J L M N R W Z) |
 * | +      | a front vowel (E I Y) |
 * | &      | a sibilant (S C G Z X J, CH, SH) |
 * | @      | T S R D L Z N J, TH, CH or SH (they make U say "oo") |
 * | %      | an ending: E, ER, ES, ED, ING or ELY (right side only) |
 *
 * Any other letter (or ') fits itself.
 *
 * @author Ken Segler
 * @copyright Copyright (c) 2026 Ken Segler
 * SPDX-License-Identifier: MIT
 */
