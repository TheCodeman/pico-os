#!/usr/bin/env python3
# Writes src/genesis/genesis_fast_68k.h: the 68000 opcode handlers a game
# used, which the board runs from SRAM (genesis_fast.h). Takes gprof flat
# profiles of build-host/genesis built with -pg (make CFLAGS="-O2 -pg"),
# e.g. a few thousand frames of a game with -S to get past its title.
#   hot_handlers.py [-m min_calls] flat1.txt [flat2.txt ...] > ../genesis_fast_68k.h
# -m leaves out handlers called fewer times than that in all (default 1).
import sys

args = sys.argv[1:]
min_calls = 1
if args[:1] == ['-m']:
    min_calls = int(args[1])
    args = args[2:]
calls = {}
for path in args:
    for line in open(path):
        f = line.split()
        if len(f) >= 4 and f[-1].startswith('m68k_op_'):
            # %time cumulative self [calls self/call total/call] name
            n = next((int(x) for x in f[3:-1] if x.isdigit()), 0) if len(f) >= 7 else 0
            calls[f[-1]] = calls.get(f[-1], 0) + n
names = sorted(n for n, c in calls.items() if c >= min_calls)
print('// Generated by host/hot_handlers.py from gprof profiles: the 68000 opcode')
print('// handlers that ran, put in the genesis_fast overlay (genesis_fast.h).')
print('#pragma once')
for n in names:
    print(f'static void {n}(void) GWENESIS_FAST;')
print(f'// {len(names)} handlers', file=sys.stderr)
