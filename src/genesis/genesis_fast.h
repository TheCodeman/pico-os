/**
 * @file genesis_fast.h
 * @brief Force-included (by CMakeLists.txt) into the core's files on the board.
 *
 * the functions declared here with GWENESIS_FAST go in the genesis_fast
 * overlay, linked to run from SRAM at the end of the framebuffer and kept in
 * flash (src/ld/section_extra_post_data.incl). genesis_pico.c copies it in
 * before the machine runs. Run from flash, these share the 16 KB XIP cache
 * with the ROM in PSRAM and the 68000's jump table, and miss all the time.
 *
 * A section attribute on a declaration carries to the definition, so the
 * core's own files need no changes for these (the Z80 interpreter's, which
 * take its struct type, are marked in Z80.c). The PC build doesn't include
 * this, and the core defines GWENESIS_FAST as nothing where it uses it.
 *
 * @author Ken Segler
 * @copyright Copyright (c) 2026 Ken Segler
 * SPDX-License-Identifier: MIT
 */
#pragma once
/// Puts a function in the genesis_fast section (run from the far end of the framebuffer).
#define GWENESIS_FAST __attribute__((section("genesis_fast")))
/// Code in the apps' shared SRAM area (src/app_overlay.h), copied in when the
/// genesis command starts: for what doesn't fit in genesis_fast.
#define GWENESIS_OV __attribute__((section("app_ov_genesis.code")))
/// The core's big variables: in the apps' shared SRAM area (src/app_overlay.h),
/// zeroed when the genesis command starts, so they hold no SRAM otherwise.
#define GENESIS_RAM __attribute__((section("app_ov_genesis.data")))

