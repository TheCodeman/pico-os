#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font (8x16) into src/font8x16.h.

By default glyphs are indexed by Latin-1 code point (0..255). With --cp437
they follow the IBM PC character set instead (code page 437: accented
letters, line and block graphics, Greek and maths symbols, and the smileys
and arrows in 1..31 and 127). Characters the first font lacks are taken from
the next font given; any still missing are left blank. Usage:
    gen_font.py /usr/share/consolefonts/Uni2-Terminus16.psf.gz > src/font8x16.h
    gen_font.py --cp437 /usr/share/consolefonts/Uni2-VGA16.psf.gz \
        /usr/share/consolefonts/FullGreek-VGA16.psf.gz > src/font8x16.h
"""
import gzip
import struct
import sys


def load_psf(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":  # PSF1
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        width, glyph_bytes, offset = 8, height, 4
        glyphs = [data[offset + i * height: offset + (i + 1) * height] for i in range(count)]
        table = {}
        if mode & 2:
            pos, idx = offset + count * height, 0
            while idx < count and pos < len(data):
                (cp,) = struct.unpack_from("<H", data, pos)
                pos += 2
                if cp == 0xFFFF:
                    idx += 1
                elif cp != 0xFFFE:
                    table.setdefault(cp, idx)
        return width, height, glyphs, table
    if data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        _, _, hsize, flags, count, glyph_bytes, height, width = struct.unpack_from("<8I", data, 0)
        glyphs = [data[hsize + i * glyph_bytes: hsize + (i + 1) * glyph_bytes] for i in range(count)]
        table = {}
        if flags & 1:
            pos, idx = hsize + count * glyph_bytes, 0
            while idx < count and pos < len(data):
                b = data[pos]
                if b == 0xFF:
                    idx += 1
                    pos += 1
                    continue
                if b == 0xFE:
                    pos += 1
                    continue
                n = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
                table.setdefault(ord(data[pos:pos + n].decode("utf-8", "replace")), idx)
                pos += n
        return width, height, glyphs, table
    raise SystemExit("not a PSF font")


# Code page 437 glyphs for 1..31 and 127, which Python's cp437 codec leaves
# as control characters.
CP437_LOW = "\u263a\u263b\u2665\u2666\u2663\u2660\u2022\u25d8\u25cb\u25d9\u2642\u2640\u266a\u266b\u263c" \
            "\u25ba\u25c4\u2195\u203c\u00b6\u00a7\u25ac\u21a8\u2191\u2193\u2192\u2190\u221f\u2194\u25b2\u25bc"


# Fonts often have the solid triangle a code point away from CP437's pointer.
ALTERNATES = {0x25BA: 0x25B6, 0x25C4: 0x25C0}


def code_point(byte, cp437):
    if not cp437:
        return byte
    if 1 <= byte <= 31:
        return ord(CP437_LOW[byte - 1])
    if byte == 0x7F:
        return 0x2302  # house
    return ord(bytes([byte]).decode("cp437"))


def main():
    args = sys.argv[1:]
    cp437 = "--cp437" in args
    paths = [a for a in args if a != "--cp437"]
    fonts = []
    for path in paths:
        width, height, glyphs, table = load_psf(path)
        if width != 8 or height != 16:
            raise SystemExit(f"{path}: need an 8x16 font, got {width}x{height}")
        fonts.append((path.rsplit("/", 1)[-1], glyphs, table))

    rows, missing, used = [], [], set()
    for byte in range(256):
        cp = code_point(byte, cp437)
        g = None
        for want in (cp, ALTERNATES.get(cp)):
            for name, glyphs, table in fonts:
                if want in table:
                    g = glyphs[table[want]]
                elif not table and want is not None and want < len(glyphs):
                    g = glyphs[want]
                if g is not None:
                    used.add(name)
                    break
            if g is not None:
                break
        if not cp437 and (byte < 0x20 or 0x7F <= byte < 0xA0):
            g = None
        if g is None:
            g = bytes(16)
            if byte and (cp437 or not (byte < 0x20 or 0x7F <= byte < 0xA0)):
                missing.append(byte)
        rows.append(g)
    if missing:
        print("missing glyphs: " + " ".join(f"0x{b:02x}" for b in missing), file=sys.stderr)

    names = [name for name, _, _ in fonts if name in used]
    print("// Generated by tools/gen_font.py" + (" --cp437" if cp437 else "") + " from " + ", ".join(names))
    if any("Terminus" in n for n in names):
        print("// Terminus Font, (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1.")
    if any("VGA" in n for n in names):
        print("// VGA fonts from the console-setup package (IBM VGA ROM style).")
    order = "IBM PC code page 437" if cp437 else "Latin-1 code point"
    print(f"// 8x16 glyphs indexed by {order}, one byte per row, MSB = left pixel.")
    print("#pragma once\n#include <stdint.h>\n")
    print("static const uint8_t font8x16[256][16] = {")
    for g in rows:
        print("    {" + ",".join(f"0x{b:02x}" for b in g) + "},")
    print("};")


if __name__ == "__main__":
    main()
